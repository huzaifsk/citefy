import { AuditReport } from '@/types/audit';

export function generateMarkdownReport(report: AuditReport): string {
  const { meta, scores, checks, priorities, crawlerMatrix, structuredData, llmInsights } = report;

  let md = `# AI SEO Audit Report: ${meta.url}\n\n`;
  md += `**Generated by:** Citeify AI SEO Audit Tool (v${meta.toolVersion})\n`;
  md += `**Date:** ${new Date(meta.timestamp).toUTCString()}\n`;
  md += `**Final URL:** ${meta.finalUrl}\n`;
  if (meta.redirectChain.length > 1) {
    md += `**Redirects:** ${meta.redirectChain.join(' → ')}\n`;
  }
  md += `**Status:** HTTP ${meta.httpStatus} (${Math.round(meta.contentLength / 1024)} KB, ${meta.timingMs}ms)\n\n`;

  md += `## 1. Executive Summary\n\n`;
  if (llmInsights?.summary) {
    md += `${llmInsights.summary}\n\n`;
  } else {
    md += `Overall readiness for AI search engines is **${scores.grade}** with an overall score of **${scores.overall}/100** (AI SEO: ${scores.ai}/100, Classic SEO: ${scores.classic}/100).\n\n`;
  }

  if (scores.criticalOverride) {
    md += `> ⚠️ **CRITICAL WARNING:** ${scores.overrideReason || 'Major search crawlers are blocked.'} Grade capped at Needs Work.\n\n`;
  }

  md += `## 2. Score Summary\n\n`;
  md += `| Metric | Score | Grade |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **Overall Score** | **${scores.overall}/100** | **${scores.grade}** |\n`;
  md += `| **AI SEO Readiness** | **${scores.ai}/100** | Primary Focus |\n`;
  md += `| **Classic SEO Health** | **${scores.classic}/100** | Secondary Focus |\n\n`;

  md += `### Category Breakdown\n\n`;
  md += `| Section | Category | Weight | Score | Pass | Warn | Fail |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
  for (const cat of Object.values(scores.categories)) {
    md += `| ${cat.section.toUpperCase()} | ${cat.name} | ${cat.weight}% | **${cat.score}/100** | ${cat.passedCount} | ${cat.warnCount} | ${cat.failCount} |\n`;
  }
  md += `\n`;

  md += `## 3. Top Priority Fixes\n\n`;
  const topFixes = priorities.slice(0, 5);
  if (topFixes.length === 0) {
    md += `*No high-priority issues detected! Site demonstrates strong baseline practices.*\n\n`;
  } else {
    topFixes.forEach((fix, index) => {
      md += `### ${index + 1}. [${fix.id}] ${fix.title}\n\n`;
      md += `- **Severity:** ${fix.severity} | **Effort:** ${fix.effort} | **Status:** ${fix.status.toUpperCase()}\n`;
      md += `- **Evidence:** ${fix.evidence}\n`;
      md += `- **Recommendation:** ${fix.recommendation}\n`;
      if (fix.snippet) {
        md += `\n\`\`\`html\n${fix.snippet}\n\`\`\`\n`;
      }
      md += `\n`;
    });
  }

  md += `## 4. AI Crawler Access Matrix\n\n`;
  md += `| Bot Name | Engine / Purpose | Type | robots.txt Rule | Live Probe | Status |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
  crawlerMatrix.forEach((bot) => {
    const probeStatus = typeof bot.liveFetchStatus === 'number' ? `HTTP ${bot.liveFetchStatus}` : bot.liveFetchStatus;
    const rule = bot.robotsStatus.toUpperCase();
    const verdict = bot.isBlocked ? '❌ Blocked' : '✅ Allowed';
    md += `| **${bot.name}** | ${bot.owner} | ${bot.botType} | ${rule} | ${probeStatus} | ${verdict} |\n`;
  });
  md += `\n`;

  md += `## 5. Structured Data Detected\n\n`;
  if (structuredData.types.length > 0) {
    md += `- **Declared Schema Types:** ${structuredData.types.join(', ')}\n`;
    md += `- **Total Entities:** ${structuredData.itemsCount}\n`;
    md += `- **Entity Linking (sameAs):** ${structuredData.hasEntityLinking ? 'Yes' : 'Missing'}\n`;
    if (structuredData.sameAsLinks.length > 0) {
      md += `- **Knowledge Graph Profiles:** ${structuredData.sameAsLinks.join(', ')}\n`;
    }
  } else {
    md += `*No Schema.org JSON-LD markup found on this page.*\n`;
  }
  md += `\n`;

  md += `## 6. All Audit Checks\n\n`;
  checks.forEach((c) => {
    const symbol = c.status === 'pass' ? '✅' : c.status === 'warn' ? '⚠️' : c.status === 'fail' ? '❌' : 'ℹ️';
    md += `### ${symbol} [${c.id}] ${c.title}\n`;
    md += `**Status:** ${c.status.toUpperCase()} | **Category:** ${c.category} | **Severity:** ${c.severity}\n\n`;
    md += `> ${c.evidence}\n\n`;
    md += `*Action:* ${c.recommendation}\n\n`;
  });

  md += `## 7. Methodology and Limitations\n\n`;
  md += `> **Important Framing:** Nobody outside the AI vendors knows the true ranking or citation algorithms of AI answer engines. This report evaluates **readiness and best practices**, never guaranteed rankings or citations.\n\n`;
  md += `- **Raw HTML Analysis:** This tool evaluates the initial server-side HTML response without executing client JavaScript, matching how most AI crawlers parse pages.\n`;
  md += `- **Scope:** Single page analysis combined with site-level files (/robots.txt, /sitemap.xml, /llms.txt).\n`;
  md += `- **Free Tier Stack:** Generated via open web standards and client-side processing.\n`;

  return md;
}

